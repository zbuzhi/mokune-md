import Foundation
func check(_ value:Bool,_ name:String){if !value{fatalError(name)};print("PASS: \(name)")}
let root=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString,isDirectory:true).resolvingSymlinksInPath()
try FileManager.default.createDirectory(at:root.appendingPathComponent("assets"),withIntermediateDirectories:true)
defer{try? FileManager.default.removeItem(at:root)}
let a=root.appendingPathComponent("a.md"),used=root.appendingPathComponent("assets/used.png"),unused=root.appendingPathComponent("assets/unused.pdf")
try Data("磁盘原文".utf8).write(to:a);try Data([1,2,3]).write(to:used);try Data([4,5,6]).write(to:unused)
let draft=ResourceDocument(id:"a",path:a.path,name:"a.md",raw:"![图](assets/used.png)未保存",revision:3,disk:nil)
let inventory=try ResourceInventory.scan(root:root,opened:[draft])
check(inventory.assets.count==2 && inventory.complete,"inventory includes image and PDF under assets")
check(inventory.documents.contains(where:{$0.id=="a" && $0.raw==draft.raw}),"unsaved draft overlays disk for reference inspection")
check(inventory.documents.contains(where:{$0.id==nil && $0.raw=="磁盘原文"}),"disk source remains checked alongside unsaved draft")
var removed=[String]()
try inventory.cleanup([unused.path],approved:[unused.path],opened:[draft]){removed.append($0.path)}
check(removed==[unused.path],"cleanup requires approved explicit selection")
check((try? inventory.cleanup([used.path],approved:[unused.path],opened:[draft]){_ in})==nil,"referenced or unapproved resource cannot be cleaned")
let changed=ResourceDocument(id:"a",path:a.path,name:"a.md",raw:"新增引用",revision:4,disk:nil)
check((try? inventory.validate(opened:[changed]))==nil,"new unsaved edit invalidates cleanup preview")
try Data("外部变化".utf8).write(to:a)
check((try? inventory.validate(opened:[draft]))==nil,"external document changes invalidate cleanup preview")
let other=root.appendingPathComponent("source.pdf");try Data([7,8]).write(to:other)
let first=try ImageImport.copy(other,beside:a,allowAny:true),second=try ImageImport.copy(other,beside:a,allowAny:true)
let original=try Data(contentsOf:other)
check(first.reference != second.reference && original==Data([7,8]),"attachment copy keeps original and disambiguates names")
let outside=try ResourceInventory.scan(root:root,opened:[draft])
check(outside.assets.contains(where:{$0.path==other.path && !$0.eligible}),"attachments outside assets are inspectable but cannot be cleaned")
check((try? ResourceInventory.scan(root:root,opened:[draft],cancelled:{true}))==nil,"cancelled scans stop without deleting files")
try FileManager.default.createSymbolicLink(at:root.appendingPathComponent("assets/link.pdf"),withDestinationURL:other)
let incomplete=try ResourceInventory.scan(root:root,opened:[draft])
check(!incomplete.complete,"symlink makes cleanup conservatively unavailable")
check((try? incomplete.cleanup([unused.path],approved:[unused.path],opened:[draft]){_ in})==nil,"incomplete scan cannot clean resources")
